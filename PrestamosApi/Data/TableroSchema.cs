namespace PrestamosApi.Data;

/// <summary>
/// Esquema del Tablero: notas/compromisos de préstamos y cuenta corriente de cobradores.
/// Idempotente; se ejecuta al iniciar la API (Program.cs). Las tablas no están en el
/// snapshot de EF, igual que el resto del esquema que se gestiona con SQL.
/// </summary>
public static class TableroSchema
{
    public const string Sql = @"

CREATE TABLE IF NOT EXISTS notasprestamo (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prestamoid integer NOT NULL REFERENCES prestamos(id) ON DELETE CASCADE,
    contenido text NOT NULL,
    fechacreacion timestamp with time zone NOT NULL DEFAULT NOW(),
    usuarioid integer NULL REFERENCES usuarios(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_notas_prestamo ON notasprestamo (prestamoid);

ALTER TABLE notasprestamo ADD COLUMN IF NOT EXISTS fechacompromiso date NULL;
ALTER TABLE notasprestamo ADD COLUMN IF NOT EXISTS montocompromiso numeric(18,2) NULL;
ALTER TABLE notasprestamo ADD COLUMN IF NOT EXISTS cumplida boolean NOT NULL DEFAULT FALSE;
ALTER TABLE notasprestamo ADD COLUMN IF NOT EXISTS fechacumplida timestamp with time zone NULL;

CREATE TABLE IF NOT EXISTS movimientoscuentacobrador (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cobradorid integer NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    tipo varchar(20) NOT NULL,
    monto numeric(18,2) NOT NULL,
    descripcion text NOT NULL,
    fecha date NOT NULL DEFAULT CURRENT_DATE,
    fechacreacion timestamp with time zone NOT NULL DEFAULT NOW(),
    usuarioid integer NULL REFERENCES usuarios(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_movcuentacobrador_cobrador ON movimientoscuentacobrador (cobradorid);
";
}
